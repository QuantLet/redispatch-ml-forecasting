logger = logging.getLogger(__name__)


def read_dataset(config: PaperConfig) -> pd.DataFrame:
    """Read the dataset for each TSO and concatenate."""
    tso_datasets = []
    for dataset_path in config.dataset_dir.glob(config.dataset_name + "_*.parquet"):
        if not dataset_path.exists():
            raise FileNotFoundError(f"Dataset file not found at {dataset_path}")
        if config.dataset_name not in dataset_path.stem:
            continue
        tso = dataset_path.stem.split("_")[-1]
        if tso == "DE" and "tennet" in dataset_path.stem.lower():
            tso = "TenneT DE"
        dataset, _ = load_dataset(dataset_path)
        dataset = to_nixtla_format(dataset)
        logger.info("Dataset loaded for TSO %s with shape %s", tso, dataset.shape)
        tso_datasets.append(dataset.assign(tso=tso))
    if len(tso_datasets) == 0:
        raise ValueError(f"No datasets found for pattern {config.dataset_name}_*.parquet in {config.dataset_dir}")
    return pd.concat(tso_datasets, ignore_index=True)


def read_training_start_date(config: PaperConfig, dataset: pd.DataFrame) -> WindowBoundary:
    """Read the training start date from the config YAML file."""
    with open(config.train_config_yaml_path, "r") as f:
        train_config = yaml.safe_load(f)
    training_windows = _compute_rolling_windows(
        data_start=dataset["ds"].min(),
        data_end=dataset["ds"].max(),
        n_train_months=train_config["n_train_months"],
        n_valid_months=train_config["n_valid_months"],
        n_test_months=train_config["n_test_months"],
    )
    selected_train_window = training_windows[0]
    logger.info(
        "Computed %d training windows and kept the first for training evaluation: [%s, %s)", 
        len(training_windows), 
        selected_train_window.train_start, 
        selected_train_window.valid_start
    )
    return selected_train_window


def _rename_index_levels(latex: str, df: pd.DataFrame) -> str:
    index_names_mapping = {
        "tso": "TSO",
        "unique_id": "Direction",
        "std": "Std Dev",
        "q_75": r"$Q_{75}$", 
        "q_90": r"$Q_{90}$",
        "q_99": r"$Q_{99}$",
        "sparsity": "Sparsity",
    }
    latex = add_index_names(latex, df)
    for current, new in index_names_mapping.items():
        latex = latex.replace(current, new)
    return latex


def run_descriptive_statistics(config: PaperConfig, whole_dataset: pd.DataFrame) -> None:
    """Compute descriptive statistics for the dataset."""
    descriptive_stats = whole_dataset.groupby(["tso", "unique_id"]).agg(
        Mean=("y", "mean"),
        Median=("y", "median"),
        q_75=("y", lambda x: x.quantile(0.75)),
        q_90=("y", lambda x: x.quantile(0.9)),
        q_99=("y", lambda x: x.quantile(0.99)),
        sparsity=("y", lambda x: (x == 0).mean()),
    )

    logger.info("Computed descriptive statistics with shape %s", descriptive_stats.shape)

    save_latex_table(
        descriptive_stats,
        path=config.tables_dir / "descriptive_statistics.tex",
        caption="Descriptive statistics of the target variable $y$ by TSO and direction.",
        formatters={
            "Mean": make_decimal_formatter(1),
            "Median": make_decimal_formatter(1),
            "q_75": make_decimal_formatter(1),
            "q_90": make_decimal_formatter(1),
            "q_99": make_decimal_formatter(1),
            "sparsity": make_percentage_formatter(2),
        },
        column_format="ll" + "r" * len(descriptive_stats.columns),
        final_form_callback=_rename_index_levels,
    )


def save_model_colors(config: PaperConfig, file_name: str, color_dict: dict[str, str] | dict[str, tuple[float, float, float, float]]) -> None:
    lines: list[str] = [
        "% Model colour definitions for mean vs median plots - generated by paper_results_cli/style.py",
        "% Paste into LaTeX preamble after: \\usepackage[dvipsnames]{xcolor}",
        "",
    ]
    for model, hex_color in color_dict.items():
        if isinstance(hex_color, tuple) and len(hex_color) == 4:
            r, g, b, _ = hex_color
        else:
            r = int(hex_color[1:3], 16) / 255
            g = int(hex_color[3:5], 16) / 255
            b = int(hex_color[5:7], 16) / 255
        # Build a valid LaTeX colour name: TitleCase, no underscores/hyphens.
        tex_name = (
            model.replace("_", " ")
            .replace("-", " ")
            .title()
            .replace(" ", "")
        )
        lines.append(
            f"\\definecolor{{{tex_name}}}{{rgb}}{{{r:.4f},{g:.4f},{b:.4f}}}"
            f"  % {model}: {hex_color}"
        )
    (config.style_dir / file_name).write_text("\n".join(lines) + "\n")


def run_mean_vs_median_plot(
    config: PaperConfig, 
    train_dataset: pd.DataFrame, 
    window_size: int = 7, 
    tso_choice: str = "50Hertz",
    n_months: int = 3,
):
    # Choose colors that do not overlap with model colors in style.py
    background_color = "#B4B4B4"  # grey for background series
    mean_color = "#1976D2"        # deep blue for mean
    median_color = "#388E3C"      # deep green for median

    """Plot the mean and median of the target variable over time, with rolling averages."""
    fig, axes = plt.subplots(nrows=2, ncols=1, figsize=(12, 12), sharex=True)
    # Pick the last 'n_months' of data for the plot
    end_date = train_dataset["ds"].max()
    start_date = end_date - pd.DateOffset(months=n_months) - pd.DateOffset(days=window_size)
    n_days = (end_date - (start_date + pd.DateOffset(days=window_size))).days
    train_dataset = train_dataset[(train_dataset["ds"] >= start_date) & (train_dataset["ds"] <= end_date)].copy()
    tso_data = train_dataset[train_dataset["tso"] == tso_choice]

    ax_up = axes[0]
    direction_data = tso_data.loc[tso_data["unique_id"] == "up", ["y", "ds"]].copy()
    ax_up.plot(direction_data["ds"], direction_data["y"], alpha=0.15, color=background_color)
    window_mean = direction_data.rolling(window=f"{window_size}d", on="ds")["y"].mean().reset_index(drop=True)
    window_median = direction_data.rolling(window=f"{window_size}d", on="ds")["y"].median().reset_index(drop=True)
    # Align rolling results with the "ds" column for correct x-axis
    ax_up.plot(direction_data["ds"], window_mean, linestyle="-", color=mean_color)
    ax_up.plot(direction_data["ds"], window_median, linestyle="--", color=median_color)

    ax_down = axes[1]
    direction_data = tso_data.loc[tso_data["unique_id"] == "down", ["y", "ds"]].copy()
    ax_down.plot(direction_data["ds"], direction_data["y"], alpha=0.15, color=background_color)
    window_mean = direction_data.rolling(window=f"{window_size}d", on="ds")["y"].mean().reset_index(drop=True)
    window_median = direction_data.rolling(window=f"{window_size}d", on="ds")["y"].median().reset_index(drop=True)
    ax_down.plot(direction_data["ds"], window_mean, linestyle="-", color=mean_color)
    ax_down.plot(direction_data["ds"], window_median, linestyle="--", color=median_color)

    ax_up.set_ylabel("Upwards Redispatch load (MWh)")
    ax_down.set_ylabel("Downwards Redispatch load (MWh)")
    ax_down.set_xlabel("Date")
    # Set major ticks every N days for hourly data
    tick_interval_days = max(1, n_days // (5 * n_months))
    tick_interval_hours = tick_interval_days * 24
    ax_down.xaxis.set_major_locator(HourLocator(interval=tick_interval_hours))
    ax_down.xaxis.set_major_formatter(DateFormatter('%m-%d'))
    for label in ax_down.get_xticklabels(which='major'):
        label.set(rotation=45, horizontalalignment='right')

    # Output color to a styles file for easy import into Latex
    save_model_colors(config, "mean_vs_median_colors.tex", {
        "meanCompPlot": mean_color,
        "medianCompPlot": median_color,
        "backgroundCompPlot": background_color,
    })

    no_legend(ax_up)
    no_legend(ax_down)

    save_figure(
        fig,
        path=config.figures_dir / "mean_vs_median.png",
        fmt=config.figure_format,
    )


def figsize_for_multiple_tsos(n: int, base_width: int = 12, base_height: int = 6, min_height: int = 3, decay: float = 0.7):
    """Dynamically adjust figure size based on number of TSOs, using a decaying schedule."""
    # Height grows sublinearly with n
    height = base_height + (max(n - 1, 0)) * base_height * decay ** (n - 1)
    height = max(height, min_height * n)
    return (base_width, height)


def run_acf_pacf_plots(
    config: PaperConfig, 
    train_dataset: pd.DataFrame, 
    figure_name: str, 
    base_width: int = 12,
    base_height: int = 6,
    tso_choice: list[str] = ["50Hertz"], 
    lags: int = 50
):
    """Plot the ACF and PACF of the target variable for the specified TSO."""

    # Choose colors
    acf_color = "#00838F"    # teal
    pacf_color = "#C48686"   # pale red
    marker_acf = "o"
    marker_pacf = "s"
    alpha = 0.7

    def custom_acf_pacf(ax, data, lags, title):
        lags = min(lags, len(data) - 1)
        acf_values = acf(data, nlags=lags, fft=True)
        pacf_values = pacf(data, nlags=lags, method="ywm")

        x_acf = np.arange(len(acf_values))
        x_pacf = np.arange(1, len(pacf_values)) + 0.15

        markerline, stemlines, baseline = ax.stem(
            x_acf, acf_values, linefmt=acf_color, markerfmt=marker_acf, basefmt=" "
        )
        plt.setp(stemlines, alpha=alpha, linewidth=1.2)
        plt.setp(markerline, markersize=6)

        ax.scatter(
            x_pacf,
            pacf_values[1:],
            color=pacf_color,
            marker=marker_pacf,
            s=28,
            zorder=4,
        )

        conf = 1.96 / np.sqrt(len(data))
        ax.axhline(conf, color="grey", linestyle="--", linewidth=0.6)
        ax.axhline(-conf, color="grey", linestyle="--", linewidth=0.6)
        ax.axhline(0, color="grey", linewidth=0.6)
        ax.set_ylabel("ACF/PACF")
        ax.set_title(title)
        ax.set_ylim(min(-0.15, pacf_values.min() - 0.05), 1.05)

    fig, axes = plt.subplots(
        len(tso_choice), 2, 
        figsize=figsize_for_multiple_tsos(n=len(tso_choice), base_width=base_width, base_height=base_height),
        sharey="all",
    )
    if len(tso_choice) == 1:
        axes = axes.reshape(1, -1)
    for i, tso in enumerate(tso_choice):
        tso_data = train_dataset[train_dataset["tso"] == tso]
        up_tso_data = tso_data[tso_data["unique_id"] == "up"]
        custom_acf_pacf(axes[i, 0], up_tso_data["y"], lags, title=f"Upwards Autocorrelation - {tso}")
        down_tso_data = tso_data[tso_data["unique_id"] == "down"]
        custom_acf_pacf(axes[i, 1], down_tso_data["y"], lags, title=f"Downwards Autocorrelation - {tso}")
        axes[i, 1].set_ylabel("")

        if i == len(tso_choice) - 1:
            axes[i, 0].set_xlabel("Lag (hours)")
            axes[i, 1].set_xlabel("Lag (hours)")

        no_legend(axes[i, 0])
        no_legend(axes[i, 1])

    save_model_colors(config, f"{figure_name}_acf_pacf_colors.tex", {
        "acfPlot": acf_color,
        "pacfPlot": pacf_color,
    })

    if len(tso_choice) > 1:
        fig.tight_layout()
    save_figure(
        fig,
        path=config.figures_dir / f"{figure_name}_acf_pacf.png",
        fmt=config.figure_format,
    )


def run_seasonality_tests(config: PaperConfig, train_dataset: pd.DataFrame) -> None:
    """Run seasonality and stationarity tests for each TSO and direction."""
    results = []
    
    for (tso, direction), group in train_dataset.groupby(["tso", "unique_id"]):
        y = group["y"].values
        # Simple ADF test for stationarity
        adf_stat, adf_pvalue, _, _, _, _ = adfuller(y)
        # Simple KPSS test for stationarity
        kpss_stat, kpss_pvalue, _, _ = kpss(y, nlags="auto")
        
        results.append({
            "tso": tso,
            "unique_id": direction,
            "ADF Stat": adf_stat,
            "ADF p-value": adf_pvalue,
            "KPSS Stat": kpss_stat,
            "KPSS p-value": kpss_pvalue,
        })
        
    results_df = pd.DataFrame(results).set_index(["tso", "unique_id"])
    logger.info("Computed seasonality/stationarity tests with shape %s", results_df.shape)
    
    save_latex_table(
        results_df,
        path=config.tables_dir / "seasonality_tests.tex",
        caption="Stationarity and seasonality tests by TSO and direction.",
        label="tab:seasonality_tests",
        formatters={
            "ADF Stat": make_decimal_formatter(2),
            "ADF p-value": make_decimal_formatter(3),
            "KPSS Stat": make_decimal_formatter(2),
            "KPSS p-value": make_decimal_formatter(3),
        },
        column_format="ll" + "r" * len(results_df.columns),
        final_form_callback=_rename_index_levels,
    )


def prewithen_series(prewhiten: str, redispatch: pd.Series) -> pd.Series:
    if prewhiten == "ar1":
        return ARIMA(redispatch, order=(1, 0, 0), trend="n").fit().resid
    elif prewhiten == "ar2":
        return ARIMA(redispatch, order=(2, 0, 0), trend="n").fit().resid
    elif prewhiten == "arma21":
        return ARIMA(redispatch, order=(2, 0, 1), trend="n").fit().resid
    elif prewhiten == "arma2024":  # SARIMA (2,0,0) × (2,0,0)_24
        return ARIMA(redispatch, order=(2, 0, 0), seasonal_order=(2, 0, 0, 24), trend="n").fit().resid
    elif prewhiten == "arma2124":  # SARIMA (2,0,0) × (2,0,1)_24
        return ARIMA(redispatch, order=(2, 0, 0), seasonal_order=(2, 0, 1, 24), trend="n").fit().resid
    elif prewhiten == "hourly_arma21":
        # Create hour-of-day dummies (0-23)
        hours = redispatch["ds"].dt.hour
        hour_dummies = pd.get_dummies(hours, prefix="hour", drop_first=True, dtype="float64")
        
        # Regress out hour-of-day effects
        model_detrend = OLS(redispatch.values, hour_dummies.values).fit()
        detrended = redispatch - model_detrend.predict(hour_dummies.values)
        
        # Apply ARMA(2,1) to residuals
        return ARIMA(detrended, order=(2, 0, 1), trend="n").fit().resid
    else:
        raise ValueError("Unknown prewhitening method: ['ar1','ar2','arma21','arma2024','arma2124','hourly_arma21']")


def run_prewhitening_diagnostics(config: PaperConfig, train_dataset: pd.DataFrame, prewhiten_model: str = "arma21") -> None:
    """Run prewhitening and compute residual diagnostics to evaluate model fit."""
    results = []
    
    for (tso, direction), group in train_dataset.groupby(["tso", "unique_id"]):
        series = group.set_index("ds")["y"]
        logger.info("Prewhitening %s - %s with %s", tso, direction, prewhiten_model)
        
        resid = prewithen_series(prewhiten_model, series)
        
        # Diagnostics
        _, adf_pvalue, _, _, _, _ = adfuller(resid)
        lb_test = acorr_ljungbox(resid, lags=[24], return_df=True)
        lb_pvalue = lb_test["lb_pvalue"].iloc[0]
        
        results.append({
            "tso": tso,
            "unique_id": direction,
            "Resid Mean": resid.mean(),
            "Resid Std": resid.std(),
            "ADF p-value": adf_pvalue,
            "Ljung-Box p-value (Lag 24)": lb_pvalue,
        })
        
    results_df = pd.DataFrame(results).set_index(["tso", "unique_id"])
    logger.info("Computed prewhitening diagnostics for shape %s", results_df.shape)
    
    save_latex_table(
        results_df,
        path=config.tables_dir / f"prewhitening_diagnostics_{prewhiten_model}.tex",
        caption=f"Residual diagnostics after prewhitening with {prewhiten_model}.",
        label=f"tab:prewhitening_{prewhiten_model}",
        formatters={
            "Resid Mean": make_decimal_formatter(2),
            "Resid Std": make_decimal_formatter(2),
            "ADF p-value": make_decimal_formatter(3),
            "Ljung-Box p-value (Lag 24)": make_decimal_formatter(3),
        },
        column_format="ll" + "r" * len(results_df.columns),
        final_form_callback=_rename_index_levels,
    )


def run(config: PaperConfig) -> None:
    whole_dataset = read_dataset(config)
    all_tsos = whole_dataset["tso"].unique().tolist()
    logger.info("Unique TSOs in dataset: %s", all_tsos)
    train_window = read_training_start_date(config, whole_dataset)
    train_dataset = whole_dataset[
        (whole_dataset["ds"] >= train_window.train_start) & 
        (whole_dataset["ds"] < train_window.valid_start)
    ].copy()
    run_descriptive_statistics(config, whole_dataset)
    run_mean_vs_median_plot(config, train_dataset, window_size=7, tso_choice="50Hertz", n_months=3)
    run_acf_pacf_plots(config, train_dataset, figure_name="50hertz", base_width=12, base_height=6, tso_choice=["50Hertz"], lags=50)
    run_acf_pacf_plots(config, train_dataset, figure_name="all_tso", base_width=12, base_height=6, tso_choice=all_tsos, lags=50)
    run_seasonality_tests(config, train_dataset)
    run_prewhitening_diagnostics(config, train_dataset, prewhiten_model="arma21")